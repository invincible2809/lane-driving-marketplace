// Dependency-free build: bundles the ES modules into one Cloudflare Worker file.
// Each module is wrapped in its own function scope, so names never collide.
// Output: dist/server/index.js, dist/server/wrangler.json, dist/drizzle/*.sql
import {readFileSync, writeFileSync, mkdirSync, cpSync, readdirSync, statSync, rmSync} from 'node:fs';
import {dirname, join, normalize, relative} from 'node:path';
const root = process.cwd();
const modules = new Map(); // path -> {code, exports}
const order = []; // dependencies before dependants
function load(path) {
  path = normalize(path);
  if (modules.has(path)) return;
  modules.set(path, null);
  let code = readFileSync(join(root, path), 'utf8');
  const deps = [];
  code = code.replace(/^import\s*\{([^}]*)\}\s*from\s*'(\.[^']+)';?\s*$/gm, (_, names, spec) => {
    const dep = normalize(join(dirname(path), spec)); deps.push(dep);
    return `const {${names.split(',').map(n => n.trim()).filter(Boolean).map(n => n.replace(/\s+as\s+/, ': ')).join(', ')}} = __mods[${JSON.stringify(dep)}];`;
  });
  if (/^import\s/m.test(code)) throw new Error(`Unsupported import form in ${path}`);
  const exports = new Set();
  code = code.replace(/^export\s*\{([^}]*)\};?\s*$/gm, (_, names) => { names.split(',').map(n => n.trim()).filter(Boolean).forEach(n => exports.add(n)); return ''; });
  for (const m of code.matchAll(/^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+([A-Za-z_$][\w$]*)/gm)) exports.add(m[1]);
  code = code.replace(/^export\s+default\s+([A-Za-z_$][\w$]*);?\s*$/gm, (_, n) => { exports.add('default: ' + n); return ''; });
  code = code.replace(/^export\s+/gm, '');
  for (const d of deps) load(d);
  modules.set(path, {code, exports: [...exports]});
  order.push(path);
}
load('worker-entry.mjs');
// Static assets embedded as base64 so binary files survive.
const assets = {};
const walk = dir => { for (const f of readdirSync(join(root, dir))) { const p = join(dir, f); if (statSync(join(root, p)).isDirectory()) walk(p); else assets[relative('public', p).split('\\').join('/')] = readFileSync(join(root, p)).toString('base64'); } };
walk('public');
let out = '// Generated by build.mjs — do not edit.\nconst __mods = {};\n';
for (const path of order) { const m = modules.get(path); out += `__mods[${JSON.stringify(path)}] = (() => {\n${m.code}\nreturn {${m.exports.join(', ')}};\n})();\n`; }
out += `const __assets = ${JSON.stringify(assets)};\nexport default __mods["worker-entry.mjs"].default;\n`;
rmSync('dist', {recursive: true, force: true});
mkdirSync('dist/server', {recursive: true});
writeFileSync('dist/server/index.js', out);
cpSync('drizzle', 'dist/drizzle', {recursive: true});
cpSync('.openai/hosting.json', 'dist/.openai/hosting.json');
writeFileSync('dist/server/wrangler.json', JSON.stringify({
  name: 'srk-driving-school', main: 'index.js', compatibility_date: '2026-10-01',
  d1_databases: [{binding: 'DB', database_name: 'lane', database_id: 'REPLACE_WITH_D1_DATABASE_ID', migrations_dir: '../drizzle'}],
  r2_buckets: [{binding: 'BUCKET', bucket_name: 'lane-private-documents'}],
  triggers: {crons: ['* * * * *']},
  vars: {SITE_MODE: 'business', EMAIL_MODE: 'preview', TRUST_PLATFORM_IDENTITY: 'false', MARKETPLACE_ENABLED: 'false'}
}, null, 2));
console.log(`Built dist/server/index.js: ${modules.size} modules, ${Object.keys(assets).length} assets.`);
